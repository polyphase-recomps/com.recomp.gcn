static unsigned char sFont[128][7]; /* bit 4 = leftmost column */
static int sFontReady;

static void build_font(void)
{
    size_t g;
    int r, k;

    for (g = 0; g < sizeof(kGlyphs) / sizeof(kGlyphs[0]); g++)
        for (r = 0; r < 7; r++)
            for (k = 0; k < 5; k++)
                if (kGlyphs[g].rows[r][k] == '#') sFont[(int)kGlyphs[g].c][r] |= (unsigned char)(0x10 >> k);
    sFontReady = 1;
}

void gcn_overlay_set(int line, const char *text)
{
    int i;

    if (line < 0 || line >= LINES) return;
    for (i = 0; text && text[i] && i < LINE_CHARS - 1; i++) sText[line][i] = text[i];
    sText[line][i] = 0;
    for (sAny = 0, i = 0; i < LINES; i++) sAny |= sText[i][0] != 0;
}

static void put(uint32_t *rgba, int stride, int w, int h, int x, int y, int scale, uint32_t color)
{
    int dx, dy;

    for (dy = 0; dy < scale; dy++)
        for (dx = 0; dx < scale; dx++)
        {
            int px = x + dx, py = y + dy;
            if (px >= 0 && py >= 0 && px < w && py < h) rgba[py * stride + px] = color;
        }
}

void gcn_overlay_text(uint32_t *rgba, int stride, int w, int h, int x0, int y0, int scale, uint32_t color, const char *t)
{
    int n = (int)strlen(t), x, y, i, r, k, advance = 6 * scale;

    if (!sFontReady) build_font();
    /* darken a band behind the text */
    for (y = y0 - scale; y < y0 + 8 * scale && y < h; y++)
        for (x = x0 - scale; x < x0 + n * advance + scale && x < w; x++)
            if (x >= 0 && y >= 0) rgba[y * stride + x] = (rgba[y * stride + x] >> 2) & 0x3F3F3F3Fu;
    for (i = 0; i < n; i++)
    {
        int c = (unsigned char)t[i];
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c >= 128) continue;
        for (r = 0; r < 7; r++)
            for (k = 0; k < 5; k++)
                if (sFont[c][r] & (0x10 >> k))
                {
                    int px = x0 + i * advance + k * scale, py = y0 + r * scale;
                    put(rgba, stride, w, h, px + 1, py + 1, scale, 0xFF000000u); /* shadow */
                    put(rgba, stride, w, h, px, py, scale, color);
                }
    }
}

void gcn_overlay_draw(uint32_t *rgba, int stride, int w, int h)
{
    int line;

    if (!sAny) return;
    for (line = 0; line < LINES; line++)
        if (sText[line][0])
            gcn_overlay_text(rgba, stride, w, h, 8, h - 12 - (line + 1) * LINE_HEIGHT, SCALE, 0xFF40FFFFu, sText[line]);
}
